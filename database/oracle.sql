-- Procedure 1: Process seat reservation with promo discount & available seats deduction
CREATE OR REPLACE PROCEDURE processSeatBooking (
    pPassengerId     IN NUMBER,
    pTripId          IN NUMBER,
    pPromoCode       IN VARCHAR2,
    pSeatNumber      IN NUMBER,
    pBookingId       OUT NUMBER,
    pFinalFare       OUT NUMBER
) AS
    vAvailableSeats  NUMBER;
    vBaseFare        NUMBER; 
    vDiscountPct     NUMBER := 0;
    vPromoId         NUMBER := NULL;
BEGIN
    SELECT availableSeats, fareAmount 
    INTO vAvailableSeats, vBaseFare 
    FROM scheduledTrip 
    WHERE tripId = pTripId FOR UPDATE;

    IF vAvailableSeats <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'No available seats on this scheduled trip.');
    END IF;

    IF pPromoCode IS NOT NULL THEN
        BEGIN
            SELECT promoId, discountPercentage 
            INTO vPromoId, vDiscountPct
            FROM promoCode
            WHERE promoCode = pPromoCode 
              AND SYSDATE BETWEEN validFrom AND validUntil
              AND currentUsage < maxUsage;
              
            UPDATE promoCode 
            SET currentUsage = currentUsage + 1 
            WHERE promoId = vPromoId;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                vDiscountPct := 0;
                vPromoId := NULL;
        END;
    END IF;

    pFinalFare := vBaseFare * (1 - (vDiscountPct / 100));

    INSERT INTO booking (passengerId, tripId, promoId, seatNumber, ticketPrice, bookingStatus)
    VALUES (pPassengerId, pTripId, vPromoId, pSeatNumber, pFinalFare, 'CONFIRMED')
    RETURNING bookingId INTO pBookingId;

    UPDATE scheduledTrip 
    SET availableSeats = availableSeats - 1 
    WHERE tripId = pTripId;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END processSeatBooking;
/

-- REPORT 1: Frequent Routes Ranked by Ticket Volume
CREATE OR REPLACE PROCEDURE FrequentRoutes AS
    CURSOR cRoutes IS
        SELECT r.routeId, r.routeName, r.origin, r.destination,
               COUNT(b.bookingId) AS totalBookings,
               NVL(SUM(b.ticketPrice), 0) AS totalRevenue
        FROM route r
        JOIN scheduledTrip st ON r.routeId = st.routeId
        JOIN booking b ON st.tripId = b.tripId
        WHERE b.bookingStatus = 'CONFIRMED'
        GROUP BY r.routeId, r.routeName, r.origin, r.destination
        ORDER BY totalBookings DESC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== FREQUENT ROUTE UTILIZATION AUDIT ===');
    FOR rec IN cRoutes LOOP
        DBMS_OUTPUT.PUT_LINE('Route #' || rec.routeId || ': ' || RPAD(rec.routeName, 35) || ' | Bookings: ' || LPAD(rec.totalBookings, 4) || ' | Revenue: LKR ' || TO_CHAR(rec.totalRevenue, '999,990.00'));
    END LOOP;
END FrequentRoutes;
/

-- REPORT 2: Financial Revenue Audit by Payment Method
CREATE OR REPLACE PROCEDURE PeriodRevenue AS
    CURSOR cRevenue IS
        SELECT p.paymentMethod,
               COUNT(p.paymentId) AS transactionCount,
               SUM(p.amountPaid) AS totalCollected
        FROM payment p
        WHERE p.paymentStatus = 'PAID'
        GROUP BY p.paymentMethod
        ORDER BY totalCollected DESC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== FINANCIAL REVENUE AUDIT BY PAYMENT MODE ===');
    FOR rev IN cRevenue LOOP
        DBMS_OUTPUT.PUT_LINE('Method: ' || RPAD(rev.paymentMethod, 12) || ' | Transactions: ' || LPAD(rev.transactionCount, 4) || ' | Collected: LKR ' || TO_CHAR(rev.totalCollected, '999,990.00'));
    END LOOP;
END PeriodRevenue;
/

-- REPORT 3: Passenger Travel History
CREATE OR REPLACE PROCEDURE PassengerHistory (pPassengerId IN NUMBER) AS
    CURSOR cHistory IS
        SELECT b.bookingId, st.tripDate, r.routeName, b.seatNumber, b.ticketPrice, b.bookingStatus
        FROM booking b
        JOIN scheduledTrip st ON b.tripId = st.tripId
        JOIN route r ON st.routeId = r.routeId
        WHERE b.passengerId = pPassengerId
        ORDER BY st.tripDate DESC;
    vName VARCHAR2(120);
BEGIN
    SELECT firstName || ' ' || lastName INTO vName FROM users WHERE userId = pPassengerId;
    DBMS_OUTPUT.PUT_LINE('=== PASSENGER TRAVEL STATEMENT FOR ' || vName || ' ===');
    FOR h IN cHistory LOOP
        DBMS_OUTPUT.PUT_LINE('Date: ' || TO_CHAR(h.tripDate, 'YYYY-MM-DD') || ' | Route: ' || RPAD(h.routeName, 30) || ' | Seat: ' || LPAD(h.seatNumber, 2) || ' | Fare: LKR ' || TO_CHAR(h.ticketPrice, '9990.00') || ' | ' || h.bookingStatus);
    END LOOP;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Passenger record #' || pPassengerId || ' not found.');
END PassengerHistory;
/

-- REPORT 4: Overdue and Upcoming Fleet Maintenance Alert
CREATE OR REPLACE PROCEDURE MaintenanceDue AS
    CURSOR cMaint IS
        SELECT v.registrationNo, v.vehicleType, v.model,
               m.maintenanceType, m.nextServiceDate,
               CASE 
                   WHEN m.nextServiceDate < SYSDATE THEN 'URGENT OVERDUE'
                   WHEN m.nextServiceDate <= SYSDATE + 7 THEN 'DUE IN 7 DAYS'
                   ELSE 'PLANNED'
               END AS urgencyStatus
        FROM vehicle v
        JOIN maintenance m ON v.vehicleId = m.vehicleId
        WHERE m.maintenanceStatus <> 'COMPLETED'
           OR m.nextServiceDate <= SYSDATE + 14
        ORDER BY m.nextServiceDate ASC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== FLEET PREVENTIVE MAINTENANCE ALERT ===');
    FOR m IN cMaint LOOP
        DBMS_OUTPUT.PUT_LINE('[' || RPAD(m.urgencyStatus, 15) || '] Reg: ' || RPAD(m.registrationNo, 12) || ' | ' || RPAD(m.vehicleType, 10) || ' | Next: ' || TO_CHAR(m.nextServiceDate, 'YYYY-MM-DD') || ' | ' || m.maintenanceType);
    END LOOP;
END MaintenanceDue;
/

-- REPORT 5: Driver Performance and Shift Duty Log
CREATE OR REPLACE PROCEDURE DriverPerformance AS
    CURSOR cDrivers IS
        SELECT d.driverId, u.firstName || ' ' || u.lastName AS driverName,
               d.licenseNo,
               COUNT(DISTINCT st.tripId) AS completedTrips,
               COUNT(DISTINCT ds.shiftId) AS totalShifts,
               NVL(SUM(fl.fuelQuantityLiters), 0) AS totalFuelLogged
        FROM driver d
        JOIN users u ON d.driverId = u.userId
        LEFT JOIN scheduledTrip st ON d.driverId = st.driverId AND st.tripStatus = 'COMPLETED'
        LEFT JOIN driverShift ds ON d.driverId = ds.driverId
        LEFT JOIN fuelLog fl ON d.driverId = fl.driverId
        GROUP BY d.driverId, u.firstName, u.lastName, d.licenseNo
        ORDER BY completedTrips DESC;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== DRIVER PERFORMANCE AND DUTY LOG ===');
    FOR dr IN cDrivers LOOP
        DBMS_OUTPUT.PUT_LINE('Driver: ' || RPAD(dr.driverName, 20) || ' | License: ' || RPAD(dr.licenseNo, 12) || ' | Trips: ' || LPAD(dr.completedTrips, 2) || ' | Shifts: ' || LPAD(dr.totalShifts, 2) || ' | Fuel: ' || TO_CHAR(dr.totalFuelLogged, '9990.0') || ' L');
    END LOOP;
END DriverPerformance;
