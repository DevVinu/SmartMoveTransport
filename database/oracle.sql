-- SmartMove Oracle Schema and Seed Data

SET DEFINE OFF;

-- Session setup
BEGIN
    EXECUTE IMMEDIATE 'ALTER SESSION SET CONTAINER = XEPDB1';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- Drop existing tables
BEGIN
    FOR cur_rec IN (
        SELECT table_name 
        FROM user_tables 
        WHERE table_name IN (
            'BUS', 'VAN', 'LUXURYCAR', 'THREEWHEEL', 'BIKE',
            'ADMIN', 'STAFF', 'DRIVER', 'PASSENGER',
            'ROUTESTOP', 'STOP', 'PAYMENT', 'BOOKING', 'FEEDBACK', 'REFUND',
            'DRIVERSHIFT', 'MAINTENANCE', 'FUELLOG', 'SCHEDULEDTRIP',
            'PROMOCODE', 'ROUTE', 'VEHICLE', 'USERS'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || cur_rec.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- Tables
-- Users
CREATE TABLE users (
    userId          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    email           VARCHAR2(120) NOT NULL UNIQUE,
    password        VARCHAR2(100) NOT NULL,
    firstName       VARCHAR2(60) NOT NULL,
    lastName        VARCHAR2(60) NOT NULL,
    phone           VARCHAR2(20) NOT NULL,
    nic             VARCHAR2(20) NOT NULL UNIQUE,
    dateOfBirth     DATE,
    role            VARCHAR2(20) DEFAULT 'PASSENGER' NOT NULL,
    accountStatus   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    createdAt       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chkUserRole CHECK (role IN ('PASSENGER', 'DRIVER', 'STAFF', 'ADMIN')),
    CONSTRAINT chkUserStatus CHECK (accountStatus IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

-- Admin
CREATE TABLE admin (
    adminId         NUMBER PRIMARY KEY,
    adminCode       VARCHAR2(20) NOT NULL UNIQUE,
    privilegeLevel  VARCHAR2(30) DEFAULT 'OPS_ADMIN' NOT NULL,
    department      VARCHAR2(60),
    CONSTRAINT fkAdminUser FOREIGN KEY (adminId) REFERENCES users(userId) ON DELETE CASCADE,
    CONSTRAINT chkPrivilege CHECK (privilegeLevel IN ('SUPER_ADMIN', 'OPS_ADMIN', 'AUDITOR'))
);

-- Staff
CREATE TABLE staff (
    staffId         NUMBER PRIMARY KEY,
    staffName       VARCHAR2(100),
    position        VARCHAR2(60) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT fkStaffUser FOREIGN KEY (staffId) REFERENCES users(userId) ON DELETE CASCADE,
    CONSTRAINT chkStaffStatus CHECK (status IN ('ACTIVE', 'INACTIVE', 'ON_LEAVE'))
);

-- Driver
CREATE TABLE driver (
    driverId          NUMBER PRIMARY KEY,
    licenseNo         VARCHAR2(30) NOT NULL UNIQUE,
    licenseNumber     VARCHAR2(30),
    licenseType       VARCHAR2(30) NOT NULL,
    licenseExpiryDate DATE NOT NULL,
    driverStatus      VARCHAR2(20) DEFAULT 'AVAILABLE',
    CONSTRAINT fkDriverUser FOREIGN KEY (driverId) REFERENCES users(userId) ON DELETE CASCADE,
    CONSTRAINT chkDriverStatus CHECK (driverStatus IN ('AVAILABLE', 'ON_DUTY', 'OFF_DUTY', 'SUSPENDED'))
);

-- Passenger
CREATE TABLE passenger (
    passengerId             NUMBER PRIMARY KEY,
    address                 VARCHAR2(255),
    preferredPaymentMethod  VARCHAR2(30) DEFAULT 'CARD',
    CONSTRAINT fkPassengerUser FOREIGN KEY (passengerId) REFERENCES users(userId) ON DELETE CASCADE,
    CONSTRAINT chkPayPref CHECK (preferredPaymentMethod IN ('CARD', 'CASH', 'WALLET', 'ONLINE'))
);

-- Vehicle
CREATE TABLE vehicle (
    vehicleId       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    registrationNo  VARCHAR2(20) NOT NULL UNIQUE,
    vehicleType     VARCHAR2(30) NOT NULL,
    model           VARCHAR2(60) NOT NULL,
    manufacturer    VARCHAR2(60) NOT NULL,
    capacity        NUMBER(4) NOT NULL,
    status          VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT chkVehType CHECK (vehicleType IN ('BUS', 'VAN', 'LUXURYCAR', 'THREEWHEEL', 'BIKE')),
    CONSTRAINT chkVehStatus CHECK (status IN ('AVAILABLE', 'ON_TRIP', 'MAINTENANCE', 'DECOMMISSIONED')),
    CONSTRAINT chkVehCapacity CHECK (capacity > 0)
);

-- Vehicle subtypes
CREATE TABLE bus (
    busId             NUMBER PRIMARY KEY,
    busType           VARCHAR2(30) DEFAULT 'AC' NOT NULL,
    standingCapacity  NUMBER(4) DEFAULT 0,
    routePermitNo     VARCHAR2(50) NOT NULL UNIQUE,
    CONSTRAINT fkBusVehicle FOREIGN KEY (busId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE
);

CREATE TABLE van (
    vanId             NUMBER PRIMARY KEY,
    vanCategory       VARCHAR2(30) DEFAULT 'STANDARD' NOT NULL,
    cargoCapacity     NUMBER(8,2) DEFAULT 0,
    CONSTRAINT fkVanVehicle FOREIGN KEY (vanId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE
);

CREATE TABLE luxuryCar (
    luxuryCarId       NUMBER PRIMARY KEY,
    luxuryCategory    VARCHAR2(30) DEFAULT 'SEDAN' NOT NULL,
    wifiAvailable     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT fkLuxuryCarVehicle FOREIGN KEY (luxuryCarId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE
);

CREATE TABLE threeWheel (
    threeWheelId      NUMBER PRIMARY KEY,
    meteredStatus     CHAR(1) DEFAULT 'Y' NOT NULL,
    canCarryLuggage   CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT fkThreeWheelVehicle FOREIGN KEY (threeWheelId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE
);

CREATE TABLE bike (
    bikeId            NUMBER PRIMARY KEY,
    helmetProvided    CHAR(1) DEFAULT 'Y' NOT NULL,
    engineCc          NUMBER(4) NOT NULL,
    CONSTRAINT fkBikeVehicle FOREIGN KEY (bikeId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE
);

-- Route
CREATE TABLE route (
    routeId                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    routeName                VARCHAR2(100) NOT NULL,
    origin                   VARCHAR2(100) NOT NULL,
    destination              VARCHAR2(100) NOT NULL,
    distanceKm               NUMBER(7,2) NOT NULL,
    estimatedDurationMinutes NUMBER(5) NOT NULL,
    baseFare                 NUMBER(10,2) NOT NULL,
    routeType                VARCHAR2(30) DEFAULT 'EXPRESSWAY' NOT NULL,
    status                   VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT chkRouteFare CHECK (baseFare > 0),
    CONSTRAINT chkRouteDist CHECK (distanceKm > 0),
    CONSTRAINT chkRouteStatus CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

-- Stops
CREATE TABLE stop (
    stopId          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    stopName        VARCHAR2(100) NOT NULL,
    locationAddress VARCHAR2(255) NOT NULL,
    latitude        NUMBER(10,6),
    longitude       NUMBER(10,6)
);

CREATE TABLE routeStop (
    routeStopId         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    routeId             NUMBER NOT NULL,
    stopId              NUMBER NOT NULL,
    stopOrder           NUMBER(3) NOT NULL,
    arrivalTimeOffset   NUMBER(5) DEFAULT 0,
    departureTimeOffset NUMBER(5) DEFAULT 0,
    CONSTRAINT fkRouteStopRoute FOREIGN KEY (routeId) REFERENCES route(routeId) ON DELETE CASCADE,
    CONSTRAINT fkRouteStopStop FOREIGN KEY (stopId) REFERENCES stop(stopId) ON DELETE CASCADE,
    CONSTRAINT uqRouteStop UNIQUE (routeId, stopOrder)
);

-- Scheduled trips
CREATE TABLE scheduledTrip (
    tripId          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    routeId         NUMBER NOT NULL,
    vehicleId       NUMBER NOT NULL,
    driverId        NUMBER NOT NULL,
    tripDate        DATE NOT NULL,
    departureTime   VARCHAR2(10) NOT NULL,
    arrivalTime     VARCHAR2(10) NOT NULL,
    availableSeats  NUMBER(4) NOT NULL,
    fareAmount      NUMBER(10,2) NOT NULL,
    tripStatus      VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT fkTripRoute FOREIGN KEY (routeId) REFERENCES route(routeId),
    CONSTRAINT fkTripVehicle FOREIGN KEY (vehicleId) REFERENCES vehicle(vehicleId),
    CONSTRAINT fkTripDriver FOREIGN KEY (driverId) REFERENCES driver(driverId),
    CONSTRAINT chkTripStatus CHECK (tripStatus IN ('SCHEDULED', 'IN_TRANSIT', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chkAvailSeats CHECK (availableSeats >= 0),
    CONSTRAINT chkTripFare CHECK (fareAmount > 0)
);

-- Driver shifts
CREATE TABLE driverShift (
    shiftId         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    driverId        NUMBER NOT NULL,
    shiftDate       DATE NOT NULL,
    startTime       VARCHAR2(10) NOT NULL,
    endTime         VARCHAR2(10) NOT NULL,
    shiftStatus     VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT fkShiftDriver FOREIGN KEY (driverId) REFERENCES driver(driverId) ON DELETE CASCADE,
    CONSTRAINT chkShiftStatus CHECK (shiftStatus IN ('SCHEDULED', 'ON_DUTY', 'COMPLETED', 'ABSENT'))
);

-- Promo codes
CREATE TABLE promoCode (
    promoId             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    promoCode           VARCHAR2(30) NOT NULL UNIQUE,
    discountPercentage  NUMBER(5,2) NOT NULL,
    validFrom           DATE NOT NULL,
    validUntil          DATE NOT NULL,
    maxUsage            NUMBER(8) DEFAULT 100 NOT NULL,
    currentUsage        NUMBER(8) DEFAULT 0 NOT NULL,
    CONSTRAINT chkDiscount CHECK (discountPercentage BETWEEN 1 AND 100),
    CONSTRAINT chkPromoUsage CHECK (currentUsage <= maxUsage)
);

-- Bookings
CREATE TABLE booking (
    bookingId       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    passengerId     NUMBER NOT NULL,
    tripId          NUMBER NOT NULL,
    promoId         NUMBER,
    bookingDate     DATE DEFAULT SYSDATE NOT NULL,
    seatNumber      NUMBER(4) NOT NULL,
    ticketPrice     NUMBER(10,2) NOT NULL,
    bookingStatus   VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT fkBookingPassenger FOREIGN KEY (passengerId) REFERENCES passenger(passengerId),
    CONSTRAINT fkBookingTrip FOREIGN KEY (tripId) REFERENCES scheduledTrip(tripId),
    CONSTRAINT fkBookingPromo FOREIGN KEY (promoId) REFERENCES promoCode(promoId),
    CONSTRAINT chkBookingStatus CHECK (bookingStatus IN ('RESERVED', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT chkSeatNum CHECK (seatNumber > 0)
);

-- Payments
CREATE TABLE payment (
    paymentId             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    bookingId             NUMBER NOT NULL UNIQUE,
    paymentDate           DATE DEFAULT SYSDATE NOT NULL,
    amountPaid            NUMBER(10,2) NOT NULL,
    paymentMethod         VARCHAR2(20) NOT NULL,
    transactionReference  VARCHAR2(60) NOT NULL UNIQUE,
    paymentStatus         VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
    CONSTRAINT fkPaymentBooking FOREIGN KEY (bookingId) REFERENCES booking(bookingId) ON DELETE CASCADE,
    CONSTRAINT chkPayMethod CHECK (paymentMethod IN ('CASH', 'CARD', 'ONLINE', 'WALLET')),
    CONSTRAINT chkPayStatus CHECK (paymentStatus IN ('PAID', 'PENDING', 'FAILED', 'REFUNDED'))
);

-- Feedback
CREATE TABLE feedback (
    feedbackId    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    passengerId   NUMBER NOT NULL,
    tripId        NUMBER NOT NULL,
    rating        NUMBER(1) NOT NULL,
    comments      VARCHAR2(500),
    feedbackDate  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fkFeedbackPassenger FOREIGN KEY (passengerId) REFERENCES passenger(passengerId),
    CONSTRAINT fkFeedbackTrip FOREIGN KEY (tripId) REFERENCES scheduledTrip(tripId),
    CONSTRAINT chkRatingScore CHECK (rating BETWEEN 1 AND 5)
);

-- Refunds
CREATE TABLE refund (
    refundId            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    bookingId           NUMBER NOT NULL,
    paymentId           NUMBER NOT NULL,
    processedByStaffId  NUMBER NOT NULL,
    refundAmount        NUMBER(10,2) NOT NULL,
    refundReason        VARCHAR2(255) NOT NULL,
    refundDate          DATE DEFAULT SYSDATE NOT NULL,
    refundStatus        VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT fkRefundBooking FOREIGN KEY (bookingId) REFERENCES booking(bookingId),
    CONSTRAINT fkRefundPayment FOREIGN KEY (paymentId) REFERENCES payment(paymentId),
    CONSTRAINT fkRefundStaff FOREIGN KEY (processedByStaffId) REFERENCES staff(staffId),
    CONSTRAINT chkRefundStatus CHECK (refundStatus IN ('PENDING', 'PROCESSED', 'REJECTED'))
);

-- Maintenance
CREATE TABLE maintenance (
    maintenanceId       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    vehicleId           NUMBER NOT NULL,
    performedByStaffId  NUMBER NOT NULL,
    maintenanceDate     DATE NOT NULL,
    maintenanceType     VARCHAR2(40) NOT NULL,
    description         VARCHAR2(255),
    cost                NUMBER(10,2) NOT NULL,
    maintenanceStatus   VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    nextServiceDate     DATE NOT NULL,
    status              VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    CONSTRAINT fkMaintVehicle FOREIGN KEY (vehicleId) REFERENCES vehicle(vehicleId) ON DELETE CASCADE,
    CONSTRAINT fkMaintStaff FOREIGN KEY (performedByStaffId) REFERENCES staff(staffId),
    CONSTRAINT chkMaintStatus CHECK (maintenanceStatus IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

-- Fuel logs
CREATE TABLE fuelLog (
    fuelLogId           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    vehicleId           NUMBER NOT NULL,
    driverId            NUMBER NOT NULL,
    refuelDate          DATE NOT NULL,
    fuelQuantityLiters  NUMBER(7,2) NOT NULL,
    litersPumped        NUMBER(7,2),
    totalCost           NUMBER(10,2) NOT NULL,
    odometerReading     NUMBER(10,2) NOT NULL,
    stationName         VARCHAR2(100) NOT NULL,
    CONSTRAINT fkFuelVehicle FOREIGN KEY (vehicleId) REFERENCES vehicle(vehicleId),
    CONSTRAINT fkFuelDriver FOREIGN KEY (driverId) REFERENCES driver(driverId),
    CONSTRAINT chkFuelQty CHECK (fuelQuantityLiters > 0),
    CONSTRAINT chkFuelCost CHECK (totalCost > 0)
);

